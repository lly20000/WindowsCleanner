namespace WindowsCleannerApp;

internal static class CleanupTargets
{
    public static IReadOnlyList<CleanupTarget> GetDefaultTargets()
    {
        var targets = new List<CleanupTarget>();

        AddIfPresent(targets, "User Temp Files", "System Cache", "Common temporary files for the current user.", true, Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "Temp");
        AddIfPresent(targets, "System Temp Files", "System Cache", "Shared temporary files created by Windows and installers.", true, Environment.GetEnvironmentVariable("WINDIR"), "Temp");
        AddIfPresent(targets, "Windows Update Cache", "System Cache", "Downloaded Windows Update packages that can usually be recreated later.", true, Environment.GetEnvironmentVariable("WINDIR"), "SoftwareDistribution", "Download");
        AddIfPresent(targets, "Prefetch Cache", "System Cache", "Windows prefetch data. Cleaning may make first launch slightly slower.", true, Environment.GetEnvironmentVariable("WINDIR"), "Prefetch");
        AddIfPresent(targets, "Crash Dumps", "Diagnostics", "Crash dump files generated by applications.", true, Environment.GetEnvironmentVariable("LOCALAPPDATA"), "CrashDumps");
        AddPerUserTargets(targets);

        return targets;
    }

    private static void AddIfPresent(List<CleanupTarget> targets, string name, string category, string description, bool defaultSelected, params string?[] parts)
    {
        var validParts = parts.Where(part => !string.IsNullOrWhiteSpace(part)).Cast<string>().ToArray();
        if (validParts.Length == 0)
        {
            return;
        }

        var path = System.IO.Path.Combine(validParts);
        targets.Add(new CleanupTarget
        {
            Name = name,
            Category = category,
            Description = description,
            DefaultSelected = defaultSelected,
            Path = path,
            Recursive = true
        });
    }

    private static void AddPerUserTargets(List<CleanupTarget> targets)
    {
        var currentUserRoot = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
        var usersRoot = Directory.GetParent(currentUserRoot)?.FullName;
        if (string.IsNullOrWhiteSpace(usersRoot) || !Directory.Exists(usersRoot))
        {
            return;
        }

        foreach (var userDirectory in Directory.GetDirectories(usersRoot))
        {
            var profileName = System.IO.Path.GetFileName(userDirectory);
            if (string.IsNullOrWhiteSpace(profileName) || IsSystemProfile(profileName))
            {
                continue;
            }

            var avdPath = System.IO.Path.Combine(userDirectory, ".android", "avd");
            var cachePath = System.IO.Path.Combine(userDirectory, ".cache");
            var codexTmpPath = System.IO.Path.Combine(userDirectory, ".codex", ".tmp");
            var downloadsPath = System.IO.Path.Combine(userDirectory, "Downloads");
            var videosPath = System.IO.Path.Combine(userDirectory, "Videos");
            var goBuildPath = System.IO.Path.Combine(userDirectory, "AppData", "Local", "go-build");
            var jetBrainsRoot = System.IO.Path.Combine(userDirectory, "AppData", "Local", "JetBrains");
            var nvidiaRoot = System.IO.Path.Combine(userDirectory, "AppData", "Local", "NVIDIA");
            var nvidiaDxCachePath = System.IO.Path.Combine(nvidiaRoot, "DXCache");
            var nvidiaGlCachePath = System.IO.Path.Combine(nvidiaRoot, "GLCache");

            targets.Add(new CleanupTarget
            {
                Name = $"Android AVD Files ({profileName})",
                Category = "Android Virtual Machine",
                Description = "Android emulator virtual device files. Clearing this directory can remove emulator images, snapshots, and local device data.",
                DefaultSelected = false,
                Path = avdPath,
                Recursive = true
            });

            targets.Add(new CleanupTarget
            {
                Name = $"User .cache Files ({profileName})",
                Category = "User Cache",
                Description = "Per-user .cache directory. This can contain application caches and temporary artifacts; keep it user-selected because some tools may recreate it slowly.",
                DefaultSelected = false,
                Path = cachePath,
                Recursive = true
            });

            targets.Add(new CleanupTarget
            {
                Name = $"Codex .tmp Files ({profileName})",
                Category = "Codex Cache",
                Description = "Per-user .codex\\.tmp directory. This contains Codex temporary files and is usually safe to clear when no related task is actively using them.",
                DefaultSelected = false,
                Path = codexTmpPath,
                Recursive = true
            });

            targets.Add(new CleanupTarget
            {
                Name = $"Downloads Files ({profileName})",
                Category = "User Downloads",
                Description = "User Downloads folder. This may contain installers, documents, archives, and other personal files, so it is always left for explicit user selection.",
                DefaultSelected = false,
                Path = downloadsPath,
                Recursive = true
            });

            targets.Add(new CleanupTarget
            {
                Name = $"Videos Files ({profileName})",
                Category = "User Videos",
                Description = "User Videos folder. This may contain personal recordings, media assets, and large video files, so it is always left for explicit user selection.",
                DefaultSelected = false,
                Path = videosPath,
                Recursive = true
            });

            targets.Add(new CleanupTarget
            {
                Name = $"Go Build Cache ({profileName})",
                Category = "Go Cache",
                Description = "Go compiler build cache under AppData\\Local\\go-build. It is usually safe to clear, but future Go builds may take longer until the cache is recreated.",
                DefaultSelected = false,
                Path = goBuildPath,
                Recursive = true
            });

            targets.Add(new CleanupTarget
            {
                Name = $"NVIDIA DXCache ({profileName})",
                Category = "NVIDIA Cache",
                Description = "NVIDIA DirectX shader cache. It is usually safe to clear, but some games or graphics applications may rebuild shader caches on next launch.",
                DefaultSelected = false,
                Path = nvidiaDxCachePath,
                Recursive = true
            });

            targets.Add(new CleanupTarget
            {
                Name = $"NVIDIA GLCache ({profileName})",
                Category = "NVIDIA Cache",
                Description = "NVIDIA OpenGL shader cache. It is usually safe to clear, but some graphics applications may need time to rebuild it afterward.",
                DefaultSelected = false,
                Path = nvidiaGlCachePath,
                Recursive = true
            });

            AddJetBrainsTargets(targets, profileName, jetBrainsRoot);
        }
    }

    private static void AddJetBrainsTargets(List<CleanupTarget> targets, string profileName, string jetBrainsRoot)
    {
        if (!Directory.Exists(jetBrainsRoot))
        {
            return;
        }

        foreach (var productDirectory in Directory.GetDirectories(jetBrainsRoot))
        {
            var productName = System.IO.Path.GetFileName(productDirectory);
            AddJetBrainsSubdirectoryTarget(
                targets,
                profileName,
                productName,
                productDirectory,
                "caches",
                "JetBrains Cache",
                "JetBrains caches directory. Usually safe to clear, but indexes and IDE caches will be rebuilt on next launch.");
            AddJetBrainsSubdirectoryTarget(
                targets,
                profileName,
                productName,
                productDirectory,
                "tmp",
                "JetBrains Temp",
                "JetBrains temporary files. Usually safe to clear.");
            AddJetBrainsSubdirectoryTarget(
                targets,
                profileName,
                productName,
                productDirectory,
                "log",
                "JetBrains Logs",
                "JetBrains IDE log files. Useful for troubleshooting, but often safe to remove when no longer needed.");
            AddJetBrainsSubdirectoryTarget(
                targets,
                profileName,
                productName,
                productDirectory,
                "database-log",
                "JetBrains Database Logs",
                "JetBrains database tool logs. Usually safe to clear.");
            AddJetBrainsSubdirectoryTarget(
                targets,
                profileName,
                productName,
                productDirectory,
                "vcsCache",
                "JetBrains VCS Cache",
                "JetBrains version control cache. Usually safe to clear, but the IDE may need time to rebuild it.");
            AddJetBrainsSubdirectoryTarget(
                targets,
                profileName,
                productName,
                productDirectory,
                "projects",
                "JetBrains Projects Cache",
                "JetBrains projects directory under AppData\\Local. Review carefully before clearing because some IDEs may store local project metadata, history, or temporary working data here.");
        }
    }

    private static void AddJetBrainsSubdirectoryTarget(
        List<CleanupTarget> targets,
        string profileName,
        string productName,
        string productDirectory,
        string subdirectoryName,
        string category,
        string description)
    {
        targets.Add(new CleanupTarget
        {
            Name = $"{productName} {subdirectoryName} ({profileName})",
            Category = category,
            Description = description,
            DefaultSelected = false,
            Path = System.IO.Path.Combine(productDirectory, subdirectoryName),
            Recursive = true
        });
    }

    private static bool IsSystemProfile(string profileName)
    {
        return profileName.Equals("All Users", StringComparison.OrdinalIgnoreCase)
            || profileName.Equals("Default", StringComparison.OrdinalIgnoreCase)
            || profileName.Equals("Default User", StringComparison.OrdinalIgnoreCase)
            || profileName.Equals("Public", StringComparison.OrdinalIgnoreCase);
    }
}
